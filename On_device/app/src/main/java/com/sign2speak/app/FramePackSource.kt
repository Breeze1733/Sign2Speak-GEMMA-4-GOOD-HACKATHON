package com.sign2speak.app

import android.content.Context
import android.graphics.Bitmap
import android.net.Uri
import android.os.SystemClock
import android.provider.OpenableColumns
import android.util.Log
import com.google.mediapipe.tasks.vision.facelandmarker.FaceLandmarkerResult
import com.google.mediapipe.tasks.vision.handlandmarker.HandLandmarkerResult
import java.io.BufferedInputStream
import java.io.EOFException
import java.io.IOException
import java.io.InputStream
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.util.concurrent.Executors
import java.util.concurrent.atomic.AtomicLong

private const val TAG = "FramePackSource"
private const val MAGIC = "S2SF"
private const val EXPECTED_VERSION = 1
private const val HEADER_SIZE = 32
private const val MAX_DIMENSION = 4096
private const val RING_BUFFER_SIZE = 3

private data class FramePackHeader(
    val width: Int,
    val height: Int,
    val frameCount: Int,
    val fps: Int,
) {
    val frameBytes: Int get() = width * height * 4
}

/**
 * Drop-in replacement for [CameraManager]: reads a local RGBA_8888 `.bin` frame pack
 * generated by `pack_frames.py`, paces playback to the video's real-time FPS timeline
 * (skipping stale frames if inference falls behind, mirroring CameraX KEEP_ONLY_LATEST),
 * and emits results through the same callback shape as the live camera.
 */
class FramePackSource(
    private val context: Context,
    private val onFrame: (
        handResult: HandLandmarkerResult?,
        faceResult: FaceLandmarkerResult?,
        timestampMs: Long,
        imgW: Int,
        imgH: Int,
        perf: PerfFrame,
        previewBitmap: Bitmap,
        frameIdx: Int,
        totalFrames: Int,
    ) -> Unit,
    private val onStateChange: (fileName: String, isPlaying: Boolean, error: String?) -> Unit = { _, _, _ -> },
) {

    private val executor = Executors.newSingleThreadExecutor()
    private val runSeq = AtomicLong(0L)

    @Volatile private var isRunning = false

    fun start(uri: Uri) {
        val currentRun = runSeq.incrementAndGet()
        isRunning = true
        val fileName = queryDisplayName(uri)
        onStateChange(fileName, true, null)

        executor.execute {
            if (!isRunning || runSeq.get() != currentRun) return@execute

            val detector = LandmarkDetector(context)
            try {
                val rawStream = context.contentResolver.openInputStream(uri)
                    ?: throw IOException("Cannot open selected file")

                detector.initialize()

                BufferedInputStream(rawStream, 256 * 1024).use { input ->
                    val header = readHeader(input)
                    Log.i(TAG, "Playing $fileName: ${header.width}x${header.height}, ${header.frameCount} frames @ ${header.fps} fps")

                    val pixelArray = ByteArray(header.frameBytes)
                    val pixelBuffer = ByteBuffer.wrap(pixelArray)
                    val bitmaps = Array(RING_BUFFER_SIZE) {
                        Bitmap.createBitmap(header.width, header.height, Bitmap.Config.ARGB_8888)
                    }

                    var nextStreamIdx = 0
                    var prevTs = -1L
                    val startWallMs = SystemClock.elapsedRealtime()

                    while (nextStreamIdx < header.frameCount && isRunning && runSeq.get() == currentRun) {
                        val elapsedMs = SystemClock.elapsedRealtime() - startWallMs
                        var targetIdx = ((elapsedMs * header.fps) / 1000L).toInt()

                        if (targetIdx < nextStreamIdx) {
                            // Ahead of video timeline: wait until nextStreamIdx's real-time slot
                            val targetWallMs = startWallMs + (nextStreamIdx.toLong() * 1000L) / header.fps
                            while (isRunning && runSeq.get() == currentRun) {
                                val remainingMs = targetWallMs - SystemClock.elapsedRealtime()
                                if (remainingMs <= 0L) break
                                try {
                                    Thread.sleep(minOf(remainingMs, 50L))
                                } catch (_: InterruptedException) {
                                    break
                                }
                            }
                            if (!isRunning || runSeq.get() != currentRun) break
                            targetIdx = nextStreamIdx
                        }

                        if (targetIdx >= header.frameCount) break

                        val framesToSkip = targetIdx - nextStreamIdx
                        if (framesToSkip > 0) {
                            skipFully(input, framesToSkip.toLong() * header.frameBytes.toLong())
                            nextStreamIdx += framesToSkip
                        }

                        readFully(input, pixelArray)
                        val currentFrameIdx = nextStreamIdx
                        nextStreamIdx++

                        val bitmap = bitmaps[currentFrameIdx % RING_BUFFER_SIZE]
                        pixelBuffer.rewind()
                        bitmap.copyPixelsFromBuffer(pixelBuffer)

                        var timestampMs = SystemClock.elapsedRealtime() - startWallMs
                        if (timestampMs <= prevTs) timestampMs = prevTs + 1L
                        prevTs = timestampMs

                        val perfTrial = PerfTrace.current
                        val observedNs = PerfTrace.now()
                        val detection = detector.detect(bitmap, timestampMs)
                        if (!isRunning || runSeq.get() != currentRun) break

                        val perf = if (BuildConfig.TIMING_ENABLED) {
                            val handFinishedNs = PerfTrace.now()
                            PerfTrace.observeHand(
                                PerfFrame(perfTrial, observedNs, handFinishedNs, currentFrameIdx.toLong()),
                                detection.handResult?.landmarks()?.isNotEmpty() == true,
                            )
                        } else {
                            PerfFrame.Disabled
                        }

                        onFrame(
                            detection.handResult,
                            detection.faceResult,
                            timestampMs,
                            header.width,
                            header.height,
                            perf,
                            bitmap,
                            currentFrameIdx + 1,
                            header.frameCount,
                        )
                    }
                }
                if (runSeq.get() == currentRun) {
                    isRunning = false
                    onStateChange(fileName, false, null)
                }
            } catch (e: Exception) {
                Log.e(TAG, "FramePack error: ${e.message}")
                if (runSeq.get() == currentRun) {
                    isRunning = false
                    onStateChange(fileName, false, e.message ?: "Error reading .bin")
                }
            } finally {
                detector.close()
            }
        }
    }

    fun stop() {
        isRunning = false
        runSeq.incrementAndGet()
    }

    fun close() {
        stop()
        executor.shutdown()
    }

    private fun queryDisplayName(uri: Uri): String {
        return try {
            context.contentResolver.query(uri, arrayOf(OpenableColumns.DISPLAY_NAME), null, null, null)?.use { cursor ->
                if (cursor.moveToFirst()) {
                    val idx = cursor.getColumnIndex(OpenableColumns.DISPLAY_NAME)
                    if (idx >= 0) cursor.getString(idx) else null
                } else null
            } ?: uri.lastPathSegment ?: "video.bin"
        } catch (_: Exception) {
            uri.lastPathSegment ?: "video.bin"
        }
    }

    private fun readHeader(input: InputStream): FramePackHeader {
        val buf = ByteArray(HEADER_SIZE)
        readFully(input, buf)

        val bb = ByteBuffer.wrap(buf).order(ByteOrder.LITTLE_ENDIAN)
        val magicBytes = ByteArray(4)
        bb.get(magicBytes)
        if (String(magicBytes, Charsets.US_ASCII) != MAGIC) {
            throw IllegalArgumentException("Invalid file format (expected S2SF .bin)")
        }

        val version = bb.int
        if (version != EXPECTED_VERSION) {
            throw IllegalArgumentException("Unsupported frame pack version: $version")
        }

        val width = bb.int
        val height = bb.int
        val frameCount = bb.int
        val fps = bb.int

        if (width !in 16..MAX_DIMENSION || height !in 16..MAX_DIMENSION) {
            throw IllegalArgumentException("Invalid dimensions: ${width}x${height}")
        }
        if (frameCount <= 0) {
            throw IllegalArgumentException("Invalid frame count: $frameCount")
        }
        val frameBytesLong = width.toLong() * height.toLong() * 4L
        if (frameBytesLong > Int.MAX_VALUE) {
            throw IllegalArgumentException("Frame too large: ${width}x${height}")
        }
        return FramePackHeader(width, height, frameCount, if (fps in 1..240) fps else 30)
    }

    private fun readFully(input: InputStream, dest: ByteArray) {
        var offset = 0
        while (offset < dest.size) {
            val read = input.read(dest, offset, dest.size - offset)
            if (read < 0) {
                throw EOFException("Unexpected EOF (read $offset/${dest.size} bytes)")
            }
            offset += read
        }
    }

    private fun skipFully(input: InputStream, totalBytes: Long) {
        var remaining = totalBytes
        while (remaining > 0L) {
            val skipped = input.skip(remaining)
            if (skipped > 0L) {
                remaining -= skipped
            } else {
                if (input.read() < 0) {
                    throw EOFException("Unexpected EOF while skipping ($remaining bytes left)")
                }
                remaining -= 1L
            }
        }
    }
}
